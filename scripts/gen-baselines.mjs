// Compiles src/drift/baselines/*.json into a TypeScript module.
//
// Two problems solved at once. The baselines used to be located at runtime via
// `import.meta.url`, which is ESM-only and blocks a CommonJS build outright. And
// a path-based lookup is how this package already shipped once with drift
// detection silently inert, because tsc does not copy .json into dist.
//
// Bundling them as code makes the data part of the module graph: it cannot go
// missing, and it loads the same way in both formats.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'drift', 'baselines');
const out = join(root, 'src', 'drift', 'baselines.generated.ts');

const entries = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const baselines = entries.map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));

const header = `// GENERATED by scripts/gen-baselines.mjs. Do not edit.
// Re-record with \`npm run record-baselines\`, then \`npm run gen:baselines\`.
import type { Baseline } from './shape.js';

export const BUNDLED_BASELINES: readonly Baseline[] = `;

writeFileSync(out, `${header}${JSON.stringify(baselines, null, 2)} as const satisfies readonly Baseline[];\n`);
console.log(`generated ${entries.length} baselines -> src/drift/baselines.generated.ts`);
